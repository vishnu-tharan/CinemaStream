/* global __dirname */
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
async function generate() {
  const source = fs.readFileSync(path.join(root, 'assets/data/movies.ts'), 'utf8');
  const entries = [...source.matchAll(/id:\s*(\d+),[\s\S]*?image:\s*require\("\.\.\/images\/([^"\n]+)"\)/g)];
  // Inception currently has no artwork and uses the in-app placeholder.
  if (entries.length !== 13) throw new Error('Review the catalog before regenerating thumbnails.');
  fs.mkdirSync(path.join(root, 'assets/images/thumbnails'), { recursive: true });
  let original = 0, optimized = 0;
  const lines = [];
  for (const [, id, filename] of entries) {
    const input = path.join(root, 'assets/images', filename);
    const output = path.join(root, 'assets/images/thumbnails', filename);
    await sharp(input).resize({ width: 360, withoutEnlargement: true }).webp({ quality: 75 }).toFile(output);
    original += fs.statSync(input).size; optimized += fs.statSync(output).size;
    lines.push(`  ${id}: require('../images/thumbnails/${filename}'),`);
  }
  fs.writeFileSync(path.join(root, 'assets/data/thumbnails.ts'), '// Generated by scripts/generate-thumbnails.cjs\nexport const movieThumbnails: Record<number, number> = {\n' + lines.join('\n') + '\n};\n');
  console.log(JSON.stringify({ films: entries.length, originalBytes: original, thumbnailBytes: optimized, reductionPercent: Math.round((1 - optimized / original) * 100) }));
}
generate().catch((error) => { console.error(error.message); process.exitCode = 1; });
