const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
async function generate() {
  const source = fs.readFileSync(path.join(root, 'assets/data/movies.js'), 'utf8');
  const entries = [
    ...source.matchAll(/id:\s*(\d+),[\s\S]*?image:\s*require\(['"]\.\.\/images\/([^'"\n]+)['"]\)/g),
  ];
  if (!entries.length) throw new Error('No catalog posters found.');
  if (new Set(entries.map((entry) => entry[1])).size !== entries.length)
    throw new Error('Duplicate movie IDs found.');
  fs.mkdirSync(path.join(root, 'assets/images/thumbnails'), { recursive: true });
  let original = 0,
    optimized = 0;
  const lines = [];
  for (const [, id, filename] of entries) {
    const input = path.join(root, 'assets/images', filename);
    const output = path.join(root, 'assets/images/thumbnails', filename);
    await sharp(input)
      .resize({ width: 520, withoutEnlargement: true })
      .webp({ quality: 85 })
      .toFile(output);
    original += fs.statSync(input).size;
    optimized += fs.statSync(output).size;
    lines.push(`  ${id}: require('../images/thumbnails/${filename}'),`);
  }
  fs.writeFileSync(
    path.join(root, 'assets/data/thumbnails.js'),
    '// Generated by scripts/generate-thumbnails.cjs\nexport const movieThumbnails = {\n' +
      lines.join('\n') +
      '\n};\n',
  );
  console.log(
    JSON.stringify({
      films: entries.length,
      originalBytes: original,
      thumbnailBytes: optimized,
      reductionPercent: Math.round((1 - optimized / original) * 100),
    }),
  );
}
generate().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
